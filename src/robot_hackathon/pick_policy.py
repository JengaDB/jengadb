"""Experimental, deterministic pick proposals from saved evidence. No robot I/O.

The policy is the rule set, not an action generated by a model. Similarity is
supporting evidence; it cannot supply current geometry or a successful grasp.
"""
import math

POLICY_VERSION = "exposed-top-first-v1"


def number(value):
    return isinstance(value, (int, float)) and not isinstance(value, bool) and math.isfinite(value)


def propose(observation, candidates, comparisons, geometry=None):
    """Return a replay-only proposal. Geometry is an optional experimental input.

    geometry[candidate_id]: verified, observation_id, setup_id, calibration_version,
    height_above_table_mm. Sam's adapter must supply measured/validated geometry;
    camera distance is never substituted for height above the table.
    """
    geometry = geometry or {}
    oid = observation["observation_id"]
    ids = [c["candidate_id"] for c in candidates]
    if len(ids) != len(set(ids)):
        raise ValueError("Duplicate candidate IDs")
    ranked, rejected = [], []
    for c in candidates:
        cid = c["candidate_id"]
        reasons = []
        for key in ("observation_id", "episode_id", "setup_id", "mode", "calibration_version"):
            if c.get(key) != observation.get(key):
                reasons.append(f"{key}_mismatch")
        if observation.get("alignment", {}).get("status") != "verified" or c.get("registration_verified") is not True:
            reasons.append("alignment_not_verified")
        if c.get("exposure", {}).get("status") != "exposed":
            reasons.append("exposure_not_verified_exposed")
        depth = c.get("depth_stats") or {}
        if not number(depth.get("median_mm")) or depth.get("median_mm", 0) <= 0:
            reasons.append("valid_depth_missing")
        label = c.get("pickability_label") or {}
        if label.get("status") == "not_pickable":
            reasons.append("labelled_not_pickable")
        g = geometry.get(cid, {})
        if (g.get("verified") is not True or
            any(g.get(k) != observation.get(k) for k in ("observation_id", "setup_id", "calibration_version")) or
            not number(g.get("height_above_table_mm")) or g.get("height_above_table_mm", -1) < 0):
            reasons.append("verified_table_relative_height_missing")
        # Only named human reviews on different observations inform this tiebreak.
        # human_default and bare pickable=true are not reviewed evidence.
        support = []
        for match in comparisons.get(cid, []):
            review = match.get("pickability_label") or {}
            if (match.get("observation_id") and match["observation_id"] != oid and
                match.get("encoder_version") == c.get("encoder_version") and
                match.get("mode") == observation.get("mode") and
                review.get("label_source") == "human" and review.get("reviewed_by") and
                review.get("status") == "pickable" and number(match.get("score"))):
                support.append(match)
        support.sort(key=lambda m: (-m["score"], m.get("candidate_id", "")))
        if reasons:
            rejected.append({"candidate_id": cid, "reasons": reasons})
            continue
        confidence = c.get("segmentation_score")
        ranked.append({"candidate_id": cid, "bbox_rgb_pixels": c.get("bbox"),
                       "height_above_table_mm": g["height_above_table_mm"],
                       "reviewed_similarity": support[0]["score"] if support else None,
                       "supporting_candidate_ids": [m["candidate_id"] for m in support],
                       "segmentation_score": confidence if number(confidence) else 0})
    ranked.sort(key=lambda r: (-r["height_above_table_mm"],
                              -(r["reviewed_similarity"] if r["reviewed_similarity"] is not None else -1),
                              -r["segmentation_score"], r["candidate_id"]))
    return {"schema_version": 1, "policy_version": POLICY_VERSION,
            "episode_id": observation["episode_id"], "observation_id": oid,
            "setup_id": observation["setup_id"], "calibration_version": observation["calibration_version"],
            "mode": observation["mode"], "replay_only": True, "executable": False,
            "decision": "propose_pick" if ranked else "request_verification",
            "selected_candidate_id": ranked[0]["candidate_id"] if ranked else None,
            "ranking": ranked, "rejected": sorted(rejected, key=lambda r: r["candidate_id"]),
            "robot_pose": None,
            "required_before_execution": ["fresh_observation", "validated_camera_to_robot_transform",
                                          "gripper_clearance_check", "designated_operator_approval"],
            "note": "Historical similarity is not a grasp outcome; this module never commands the robot."}
